import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
test("library backup downloads, confirms safe copies, skips conflicts and rejects corrupted input", async ({ page }) => {
  await page.goto("/");
  await expect(page.locator(".plan-row")).toHaveCount(1);
  await page.getByRole("button", { name: "Резервная копия", exact: true }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("menuitem", { name: "Скачать все данные" }).click();
  const file = await download;
  const raw = await readFile((await file.path())!, "utf8");
  const backup = JSON.parse(raw);
  expect(backup.app).toBe("IPOS.Plan"); expect(backup.activity.length).toBeGreaterThan(0);
  await page.locator('input[aria-label="Файл резервной копии"]').setInputFiles({ name: "library.json", mimeType: "application/json", buffer: Buffer.from(raw) });
  await expect(page.getByRole("dialog")).toContainText("Существующие планы и история останутся");
  await expect(page.getByRole("radio", { name: /Добавить новыми копиями/ })).toBeChecked();
  await expect(page.locator(".plan-row")).toHaveCount(1);
  await page.getByRole("button", { name: "Подтвердить восстановление" }).click();
  await expect(page.getByRole("dialog")).toContainText("Восстановлено планов: 1");
  await page.getByRole("button", { name: "Готово", exact: true }).click();
  await expect(page.locator(".plan-row")).toHaveCount(2);
  await page.locator('input[aria-label="Файл резервной копии"]').setInputFiles({ name: "library.json", mimeType: "application/json", buffer: Buffer.from(raw) });
  await page.getByRole("radio", { name: /Пропустить планы/ }).check();
  await page.getByRole("button", { name: "Подтвердить восстановление" }).click();
  await expect(page.getByRole("dialog")).toContainText("Пропущено планов: 1");
  await page.getByRole("button", { name: "Готово", exact: true }).click();
  await page.locator('input[aria-label="Файл резервной копии"]').setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{"formatVersion":999}') });
  await expect(page.locator('[data-sonner-toast][data-type="error"]')).toContainText("Несовместимая");
  await expect(page.locator(".plan-row")).toHaveCount(2);
});

test("built-in and custom templates insert editable whole briefs with fresh IDs; blank task remains", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Новый план", exact: true }).click();
  await page.getByRole("button", { name: "Шаблоны", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Задача из шаблона" });
  await dialog.getByLabel("Шаблон", { exact: true }).selectOption("builtin-3");
  await expect(dialog.locator(".task-brief")).toHaveCount(1);
  await expect(dialog).toContainText("Размеры и форматы");
  await dialog.getByRole("button", { name: "Вставить задачу" }).click();
  const briefs = page.locator('.editor-workspace > .plan-paper .task-brief');
  await expect(briefs).toHaveCount(1);
  await briefs.first().getByRole("textbox", { name: /^Название:/ }).fill("Афиша — День студента");
  await briefs.first().getByRole("button", { name: /^Действия задачи:/ }).click();
  await page.getByRole("menuitem", { name: "Сохранить как шаблон" }).click();
  await page.getByLabel("Название шаблона", { exact: true }).fill("Моя афиша");
  await page.getByRole("button", { name: "Сохранить шаблон", exact: true }).click();
  await page.getByRole("button", { name: "Шаблоны", exact: true }).click();
  await dialog.getByLabel("Шаблон", { exact: true }).selectOption({ label: "Моя афиша" });
  await expect(dialog.getByRole("checkbox")).not.toBeChecked();
  await dialog.getByRole("button", { name: "Вставить задачу" }).click();
  await expect(briefs).toHaveCount(2);
  expect(await briefs.evaluateAll(nodes => new Set(nodes.map(n => n.getAttribute("data-plan-block"))).size)).toBe(2);
  await expect(page.locator('.save-status[data-state="saved"]')).toBeVisible();
  await page.reload();
  await expect(briefs).toHaveCount(2);
  await page.getByRole("button", { name: "Задача", exact: true }).click();
  await expect(briefs).toHaveCount(3);
  await expect(page.getByRole("textbox", { name: "Название: Новая задача", exact: true })).toBeVisible();
});
